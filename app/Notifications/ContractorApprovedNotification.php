<?php

namespace App\Notifications;

use Illuminate\Bus\Queueable;
use Illuminate\Notifications\Messages\MailMessage;
use Illuminate\Notifications\Notification;

class ContractorApprovedNotification extends Notification
{
    use Queueable;

    /**
     * Create a new notification instance.
     */
    public function __construct()
    {
        //
    }

    /**
     * Get the notification's delivery channels.
     *
     * @param  mixed  $notifiable
     * @return array
     */
    public function via($notifiable)
    {
        return ['mail'];
    }

    /**
     * Get the mail representation of the notification.
     *
     * @param  mixed  $notifiable
     * @return \Illuminate\Notifications\Messages\MailMessage
     */
    public function toMail($notifiable)
    {
        $name = $notifiable->name ?? 'Contractor';

        return (new MailMessage)
            ->subject('Account Approved - Welcome to the Platform')
            ->greeting("Hello {$name},")
            ->line('Congratulations! Your documents and credentials have been verified and approved by the administrator.')
            ->line('Your account is now active. You can start reviewing maintenance requests and submitting job quotes.')
            ->action('Access Your Dashboard', url('/login'))
            ->line('Thank you for partnering with us!');
    }

    /**
     * Get the array representation of the notification.
     *
     * @param  mixed  $notifiable
     * @return array
     */
    public function toArray($notifiable)
    {
        return [
            //
        ];
    }
}